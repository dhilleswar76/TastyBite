// Smart Match Function: matches any dish name to the exact corresponding high-res food photo
export const smartMatchDishImage = (dishName = '', category = '', tag = '') => {
  const query = dishName.toLowerCase().trim();
  if (!query) return RESTAURANT_FOOD_ASSETS[0].file;

  let bestMatch = null;
  let highestScore = 0;

  for (const asset of RESTAURANT_FOOD_ASSETS) {
    let score = 0;

    // Check exact name match
    if (query.includes(asset.name.toLowerCase()) || asset.name.toLowerCase().includes(query)) {
      score += 50;
    }

    // Check keyword matches
    for (const kw of asset.keywords) {
      if (query.includes(kw)) {
        score += kw.length * 3;
      }
    }

    // Category boost
    if (category && asset.category === category) {
      score += 5;
    }

    // Tag boost
    if (tag && asset.tag === tag) {
      score += 3;
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = asset;
    }
  }

  return bestMatch ? bestMatch.file : RESTAURANT_FOOD_ASSETS[0].file;
};
